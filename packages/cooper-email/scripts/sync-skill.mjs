// Copy skills/cooper-email/SKILL.md (the copy skills.sh indexes) into the CLI bundle.
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const root = join(here, "..", "..", "..");
const skill = readFileSync(join(root, "skills", "cooper-email", "SKILL.md"), "utf8");
const pkg = JSON.parse(readFileSync(join(here, "..", "package.json"), "utf8"));
const banner = "// Generated by packages/cooper-email/scripts/sync-skill.mjs. Do not edit.\n";
writeFileSync(
  join(here, "..", "src", "cli", "skill-content.ts"),
  `${banner}export const SKILL_MD = ${JSON.stringify(skill)};\n`,
);
writeFileSync(
  join(here, "..", "src", "cli", "version.ts"),
  `${banner}export const VERSION = ${JSON.stringify(pkg.version)};\n`,
);
